-- Tablas para PostgreSQL (Supabase).
-- La base ya existe en el proyecto de Supabase. No crea el servidor.

CREATE TABLE IF NOT EXISTS actividades (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo_segmento INTEGER NOT NULL,
  segmento VARCHAR(200) NOT NULL,
  codigo_familia INTEGER NOT NULL,
  familia VARCHAR(200) NOT NULL,
  codigo_clase INTEGER NOT NULL,
  clase VARCHAR(200) NOT NULL,
  codigo_producto INTEGER NOT NULL,
  producto VARCHAR(200) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_actividades_producto ON actividades (producto);
CREATE INDEX IF NOT EXISTS idx_actividades_codigo_producto ON actividades (codigo_producto);

CREATE TABLE IF NOT EXISTS ofertas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  consecutivo VARCHAR(20) NOT NULL UNIQUE,
  objeto VARCHAR(150) NOT NULL,
  descripcion VARCHAR(400) NOT NULL,
  moneda VARCHAR(3) NOT NULL,
  presupuesto NUMERIC(15,2) NOT NULL,
  actividad_id INTEGER NOT NULL REFERENCES actividades (id),
  fecha_inicio DATE NOT NULL,
  hora_inicio TIME NOT NULL,
  fecha_cierre DATE NOT NULL,
  hora_cierre TIME NOT NULL,
  estado VARCHAR(20) NOT NULL,
  creado_en TIMESTAMP NOT NULL,
  actualizado_en TIMESTAMP NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_ofertas_objeto ON ofertas (objeto);
CREATE INDEX IF NOT EXISTS idx_ofertas_actividad ON ofertas (actividad_id);

CREATE TABLE IF NOT EXISTS ofertas_documentos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  licitacion_id INTEGER NOT NULL REFERENCES ofertas (id),
  titulo VARCHAR(100) NOT NULL,
  descripcion VARCHAR(200) NOT NULL,
  archivo VARCHAR(255) NOT NULL,
  contenido BYTEA,
  creado_en TIMESTAMP NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_documentos_licitacion ON ofertas_documentos (licitacion_id);

CREATE TABLE IF NOT EXISTS secuencias (
  anio CHAR(2) PRIMARY KEY,
  ultimo INTEGER NOT NULL
);
